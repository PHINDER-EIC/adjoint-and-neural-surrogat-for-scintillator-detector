#!/usr/bin/env python3
"""
PHINDER Stage-6B: high-dimensional adjoint optical-geometry atlas.

This script is the bridge between the validated Stage-6A weighted adjoint
transport and the geometry-conditioned Stage-6 v3 neural operator.

The design space is a fixed five-segment guide (six ordered vertices):
  start -> turn1 -> turn2 -> turn3 -> turn4 -> terminal

Continuous variables are
  cell_x, cell_y, cell_z,
  guide width w,
  global bend radius R (sampled through R/w),
  four internal x coordinates,
  four ordered internal y coordinates.

Thus the default geometry space has 13 continuous degrees of freedom.
Guide 0 lies on the +z face; guide 1 is the exact x-mirror on the -z face.

Two subcommands are intended for normal use:

  make-bank : generate a constrained, space-filling Sobol geometry bank and
              preflight all selected geometries before any photon transport.

  run       : run the weighted adjoint whole-volume field for each geometry
              and write one multi-geometry HDF5 atlas with checkpoint/resume.

The atlas stores the full field h(x,y,z,t), p(x,y,z), timing moments and
Monte-Carlo rate uncertainties for channel 0.  Channel 1 is obtained exactly
by mirror symmetry in the current detector family.

Important implementation choices
--------------------------------
* All geometries in the same split use the same scrambled Halton launch prefix
  and the same stateless keyed analog RNG seed.  This correlates Monte-Carlo
  noise across geometries without biasing expectations.
* validation and test use different seeds from training.
* grid dimensions are fixed in normalized coordinates: every geometry uses
  nx x ny x nz voxels spanning its own physical cell dimensions.
* the guide bank is generated by rejection from a 13-D Sobol sequence and
  then thinned with greedy maximin selection over the accepted physical design
  space.  Invalid fillets, overlapping bends and out-of-face guide footprints
  are rejected before transport.
* completed per-geometry checkpoints are retained by default so statistics can
  later be increased without restarting that geometry.

This module deliberately reuses the already-tested geometry builder from
phinder_stage6_operator_atlas_v3.py and the validated weighted-branching field
transport from phinder_stage6_adjoint_field.py rather than duplicating either
physics implementation.
"""
