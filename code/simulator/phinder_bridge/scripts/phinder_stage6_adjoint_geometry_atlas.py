def _compute_products(raw: dict, spec, path0, path1, cfg: dict, merged: dict, args,
                      fingerprint: str, launch_seed: int, physics_seed: int, elapsed: float):
    N = int(merged["n"])
    if N <= 0:
        raise RuntimeError(f"{raw['id']}: no successful adjoint roots")
    shape = tuple(int(x) for x in cfg["grid_shape"])
    cell = np.asarray(spec.cell_cm, float)

    # Rebuild the scene only to obtain the exact terminal CORE dimensions used
    # by the validated reciprocity normalization.
    _, _, core_w, core_h = field.base._build_from_cfg(cfg)
    area = float(core_w * core_h)
    reciprocity_norm = 0.25 * area * (float(CORE.refractive_index) / float(EJ204.refractive_index)) ** 2

    spacing = cell / np.asarray(shape, float)
    voxel_volume = float(np.prod(spacing))
    cell_volume = float(np.prod(cell))

    meanL = merged["sumL"] / N
    varL = np.maximum((merged["sumL2"] - merged["sumL"] ** 2 / N) / max(N - 1, 1), 0.0)
    seL = np.sqrt(varL / N)
    p = reciprocity_norm * meanL / voxel_volume
    p_se = reciprocity_norm * seL / voxel_volume
    m1 = reciprocity_norm * (merged["sumLt"] / N) / voxel_volume
    mean_t = np.divide(merged["sumLt"], merged["sumL"], out=np.full(shape, np.nan), where=merged["sumL"] > 0)
    h = reciprocity_norm * merged["hist"] / (N * voxel_volume * float(args.dt_ns))
    rel_se = np.divide(p_se, p, out=np.full(shape, np.nan), where=p > 0)
    touch_fraction = merged["hit_roots"] / N
    p_from_time = np.sum(h, axis=-1) * float(args.dt_ns)
    coverage = np.divide(p_from_time, p, out=np.full(shape, np.nan), where=p > 0)

    pvol = reciprocity_norm * (merged["sumLvol"] / N) / cell_volume
    varLvol = max((merged["sumLvol2"] - merged["sumLvol"] ** 2 / N) / max(N - 1, 1), 0.0)
    pvol_se = reciprocity_norm * math.sqrt(varLvol / N) / cell_volume
    tvol = float(merged["sumLtvol"] / merged["sumLvol"]) if merged["sumLvol"] > 0 else float("nan")

    terminal_mean = {str(k): float(v) / N for k, v in merged["terminal_weight"].items()}
    bulk_mean = float(merged["bulk_absorbed_weight"]) / N
    accounted = bulk_mean + sum(terminal_mean.values())
    unresolved = terminal_mean.get("UNRESOLVED_MAX_TIME", 0.0) + terminal_mean.get("UNRESOLVED_MAX_STEPS", 0.0)

    finite_rel = rel_se[np.isfinite(rel_se)]
    med_rel = float(np.median(finite_rel)) if finite_rel.size else float("nan")
    p90_rel = float(np.quantile(finite_rel, 0.90)) if finite_rel.size else float("nan")

    return dict(
        p=p, p_se=p_se, rel_se=rel_se, m1=m1, mean_t=mean_t, h=h,
        roots_touching=merged["hit_roots"], touch_fraction=touch_fraction,
        time_coverage=coverage,
        x_edges=np.linspace(0.0, cell[0], shape[0] + 1),
        y_edges=np.linspace(0.0, cell[1], shape[1] + 1),
        z_edges=np.linspace(0.0, cell[2], shape[2] + 1),
        summary=dict(
            geometry_id=str(raw["id"]), split=str(raw["split"]),
            root_launches_successful=N, root_launches_attempted=int(merged["attempted"]),
            halton_prefix_length=int(merged["next_id"]),
            elapsed_this_invocation_s=float(elapsed),
            reached_scintillator_fraction=float(merged["reached_scint"] / N),
            unresolved_weight_per_root=float(unresolved),
            weight_accounting_per_root=float(accounted),
            deterministic_splits_per_root=float(merged["splits"] / N),
            analog_fallbacks_per_root=float(merged["analog_fallbacks"] / N),
            volume_mean_p=float(pvol), volume_mean_p_se=float(pvol_se),
            volume_mean_transport_time_ns=float(tvol),
            voxel_relative_se_median=float(med_rel), voxel_relative_se_p90=float(p90_rel),
            reciprocity_prefactor_cm2=float(reciprocity_norm),
            launch_seed=int(launch_seed), physics_seed=int(physics_seed),
            config_fingerprint=str(fingerprint),
        ),
    )


def _delete_if_exists(group, name):
    if name in group:
        del group[name]


def _write_geometry_group(f: h5py.File, raw: dict, spec, path0, path1, prod: dict, args):
    root = f.require_group("geometries")
    gid = str(raw["id"])
    if gid in root:
        del root[gid]
    g = root.create_group(gid)
    s = prod["summary"]
