def cmd_self_test(args):
    with tempfile.TemporaryDirectory(prefix="phinder_stage6B_bank_") as td:
        t = Path(td)
        bank_path = t / "tiny_bank.json"
        mb = SimpleNamespace(
            ranges_json=args.ranges_json,
            train=3, val=1, test=1,
            accepted_pool_factor=2.0,
            sobol_seed=629123, split_seed=629124,
            max_candidates=20000, candidate_batch=512,
            facets_per_90=16, verbose=False,
            output=bank_path,
        )
        cmd_make_bank(mb)
        bank = _load_bank(bank_path)
        if len(bank["geometries"]) != 5:
            raise AssertionError("tiny bank size")
        for raw in bank["geometries"]:
            spec, p0, p1 = _preflight_raw(raw, 16, full_scene=True)
            if len(spec.turns_xy_cm) != 4:
                raise AssertionError("turn count")
            if not np.allclose(p1.points[:, 0], spec.cell_cm[0] - p0.points[:, 0]):
                raise AssertionError("x mirror points")
            if not np.allclose(p1.points[:, 1], p0.points[:, 1]):
                raise AssertionError("y mirror points")
        print("Stage-6B geometry-atlas self-test PASS")
        print("  constrained Sobol bank generation PASS")
        print("  five-segment rounded-guide preflight PASS")
        print("  exact x-mirror guide construction PASS")
        print("  no photons were transported")


